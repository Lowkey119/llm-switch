let lang: Lang = "zh";
const subs = new Set<() => void>();

export function getLang(): Lang {
  return lang;
}

/** App 拉到 `ui.lang` 偏好后写入；变化即广播订阅方重渲染。 */
export function setLang(l: Lang) {
  if (l === lang) return;
  lang = l;
  subs.forEach((f) => f());
}

export function t(key: string): string {
  const e = DICT[key];
  if (!e) return key;
  return lang === "zh" ? e[0] : e[1];
}

/**
 * 带插值的翻译：模板里的 `{name}` 换成 vars 里的值。
 * 变量可以是字符串，也可以是 JSX 片段——句子里带 <b>/<Risk> 的富文本靠这个，
 * 否则只能把整句拆成碎片，英文语序就没法读了。返回数组，调用方直接渲染。
 */
export function tf(key: string, vars?: Record<string, unknown>): ReactNode[] {
  const tpl = t(key);
  if (!vars) return [tpl];
  const out: ReactNode[] = [];
  const re = /\{(\w+)\}/g;
  let last = 0;
  let m: RegExpExecArray | null;
  while ((m = re.exec(tpl))) {
    if (m.index > last) out.push(tpl.slice(last, m.index));
    const v = vars[m[1]];
    const node = (v !== undefined ? v : m[0]) as ReactNode;
    // 插进来的元素必须带 key：tf 返回的是数组，React 对无 key 的数组子元素必报警
    // （各页 `tf("...", { risk: <Risk>…</Risk> })` 都是这个形状）。占位名天然唯一，就地补上。
    out.push(isValidElement(node) ? cloneElement(node, { key: m[1] }) : node);
    last = m.index + m[0].length;
  }
  if (last < tpl.length) out.push(tpl.slice(last));
  return out;
}

/** 纯字符串版插值（toast、title 这类只能收 string 的地方）。 */
export function ts(key: string, vars?: Record<string, string | number>): string {
  return tf(key, vars)
    .map((x) => String(x))
    .join("");
}

function subscribe(cb: () => void) {
  subs.add(cb);
  return () => {
    subs.delete(cb);
  };
}

/** 组件侧入口：语言变化即重渲染（与主题 lib/theme.ts 同型）。 */
export function useI18n() {
  const cur = useSyncExternalStore(subscribe, getLang);
  return { t, lang: cur };
}
